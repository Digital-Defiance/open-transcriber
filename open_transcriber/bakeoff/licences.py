"""Licence audit of the running environment: MIT, BSD or Apache-2.0 only.

Reads every installed distribution's metadata (``importlib.metadata``) and maps its ``License-Expression``,
its Trove licence classifiers and its ``License`` field to one of the allowed families. Anything it can't
place, or anything copyleft, fails and is named.

    python -m open_transcriber.bakeoff.licences            # check, exit 1 on a failure
    python -m open_transcriber.bakeoff.licences --write    # also write env/LICENSES-eval.md
"""

from __future__ import annotations

import argparse
import importlib.metadata as md
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ALLOWED = ("MIT", "BSD", "Apache-2.0")

# SPDX ids we accept, by family.
_SPDX = {
    "MIT": "MIT", "MIT-0": "MIT",
    "BSD-2-Clause": "BSD", "BSD-3-Clause": "BSD", "0BSD": "BSD",
    "Apache-2.0": "Apache-2.0",
}
# Trove classifiers (the part after "License :: ").
_CLASSIFIER_OK = {
    "OSI Approved :: MIT License": "MIT",
    "OSI Approved :: MIT No Attribution License (MIT-0)": "MIT",
    "OSI Approved :: BSD License": "BSD",
    "OSI Approved :: Apache Software License": "Apache-2.0",
}
_COPYLEFT = re.compile(r"\b(GPL|LGPL|AGPL|MPL|Mozilla|EUPL|CDDL|EPL|GNU)\b", re.IGNORECASE)
# Free-text License fields seen in practice.
_TEXT = [
    (re.compile(r"^\s*(the\s+)?mit(\s+license)?\s*$", re.IGNORECASE), "MIT"),
    (re.compile(r"^\s*(new\s+|modified\s+|simplified\s+)?bsd(\s*[-\s]?\s*[23]-?clause)?(\s+license)?\s*$",
                re.IGNORECASE), "BSD"),
    (re.compile(r"^\s*[23]-clause\s+bsd(\s+license)?\s*$", re.IGNORECASE), "BSD"),
    (re.compile(r"^\s*apache(\s+software)?(\s+license)?[\s,-]*(v(ersion)?\s*)?2(\.0)?\s*$", re.IGNORECASE),
     "Apache-2.0"),
]


@dataclass(frozen=True)
class Verdict:
    name: str
    version: str
    family: str | None  # MIT, BSD or Apache-2.0; None when it fails
    evidence: str


def _spdx_family(expression: str) -> str | None:
    """Family of an SPDX expression: any OR alternative whose AND terms are all allowed."""
    cleaned = expression.replace("(", " ").replace(")", " ")
    for alternative in re.split(r"\s+OR\s+", cleaned.strip(), flags=re.IGNORECASE):
        terms = [t.strip() for t in re.split(r"\s+AND\s+", alternative, flags=re.IGNORECASE) if t.strip()]
        families = [_SPDX.get(t) for t in terms]
        if terms and all(families):
            return families[0]
    return None


def classify(name: str, version: str, expression: str | None, license_field: str | None,
             classifiers: list[str]) -> Verdict:
    """Place one distribution's licence metadata in an allowed family, or fail it."""
    if expression:
        family = _spdx_family(expression)
        return Verdict(name, version, family, f"License-Expression: {expression}")
    licence_classifiers = [c.split("License ::", 1)[1].strip() for c in classifiers if c.startswith("License ::")]
    if any(_COPYLEFT.search(c) for c in licence_classifiers):
        return Verdict(name, version, None, "classifier: " + "; ".join(licence_classifiers))
    known = [_CLASSIFIER_OK[c] for c in licence_classifiers if c in _CLASSIFIER_OK]
    if known and len(known) == len(licence_classifiers):
        return Verdict(name, version, known[0], "classifier: " + "; ".join(licence_classifiers))
    text = (license_field or "").strip()
    if text and not _COPYLEFT.search(text):
        first = text.splitlines()[0]
        for pattern, family in _TEXT:
            if pattern.match(first):
                return Verdict(name, version, family, f"License: {first}")
    return Verdict(name, version, None, f"unplaced: License={text[:60]!r} classifiers={licence_classifiers}")


def audit() -> list[Verdict]:
    """Verdicts for every distribution installed in the running environment, sorted by name."""
    verdicts = []
    for dist in md.distributions():
        meta = dist.metadata
        verdicts.append(classify(
            meta["Name"], dist.version, meta.get("License-Expression"), meta.get("License"),
            meta.get_all("Classifier") or [],
        ))
    return sorted(verdicts, key=lambda v: v.name.lower())


BUNDLED_NOTE = """\
Bundled native libraries: the numpy and scipy wheels for macOS arm64 carry OpenBLAS (BSD-3-Clause) and GCC's
runtime libraries libgfortran, libquadmath and libgcc_s (GPL-3.0 with the GCC Runtime Library Exception, which
lets programs under any licence use them). Every numpy and scipy wheel ships them; the packages are BSD.
"""


def write_report(verdicts: list[Verdict], path: Path) -> None:
    """Write the audit as a Markdown table."""
    lines = [
        "# Licences in the judge's evaluation environment",
        "",
        f"Generated by `python -m open_transcriber.bakeoff.licences --write` with Python {sys.version.split()[0]}.",
        "Allowed: MIT, BSD or Apache-2.0.",
        "",
        "| Package | Version | Licence | Evidence |",
        "|---|---|---|---|",
    ]
    for v in verdicts:
        lines.append(f"| {v.name} | {v.version} | {v.family or 'NOT ALLOWED'} | {v.evidence} |")
    lines += ["", BUNDLED_NOTE]
    path.write_text("\n".join(lines), encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="write env/LICENSES-eval.md")
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("env") / "LICENSES-eval.md")
    args = parser.parse_args(argv)
    verdicts = audit()
    bad = [v for v in verdicts if v.family is None]
    for v in verdicts:
        print(f"{'OK ' if v.family else 'BAD'} {v.name}=={v.version}: {v.family or v.evidence}")
    if args.write:
        write_report(verdicts, args.output)
        print(f"wrote {args.output}")
    if bad:
        print("Not allowed: " + ", ".join(v.name for v in bad), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
