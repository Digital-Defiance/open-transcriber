"""Resolve frozen-split member ids into the ``{"id","wav","labels"}`` clips train/eval consume.

The frozen dev splits (``dev_splits``) name member *ids* (e.g. ``sampler-90000000``, ``rwc-g001``); the probe
trainer/evaluator (``probe/data.py``) want clip dicts with a wav path and a ``labels`` record. This module is
the bridge, and is deliberately **design-neutral**: it only *locates* files the pre-registration already
declares. It does not decide how any label is scored.

Two sides, per the pre-registration:

- **TRAIN**: sampler-dev + soulx-dev. Both are generated by the material scripts
  (``make_sampler_audio`` / ``make_soulx_slice``), which write exact ``labels.json`` by construction, so the
  train side needs no label adapter — only generation and resolution.
- **REAL-DEV (eval)**: rwc-other-dev + karaoke-dev. These are CC BY-NC references (``refs.py``), note-only
  TSVs with no beat/chord/key/duration. ``reference_to_eval_labels`` turns a reference TSV into melody-only
  eval labels under the owner's **Option 1** decision (melody-only real-dev eval; see
  ``.agents/tasks/ear-bakeoff-2026-10-20/data-pipeline-design-2026-10-21.md``): notes only, the karaoke
  freestyle mask honored, and beats/downbeats/chords/key explicitly NOT-LABELLED (``None``) so the scorer
  excludes them rather than scoring them as all-wrong. Nothing in this module trains on RWC/karaoke.

The sealed TEST partitions (RWC-Pop, rwc-other-test, USDX-test, COTB) are never resolved: ``assemble`` refuses
any sealed id, mirroring the guard in ``probe/data.py``.
"""

from __future__ import annotations

from pathlib import Path

from . import dev_splits, notes_io, paths

#: Small tail (seconds) added past the last note offset to set a melody-only clip's duration.
TAIL = 0.5


def _sampler_dir() -> Path:
    """``.cache/ear/sampler`` without importing the music21-dependent material script."""
    return paths.copyist_root() / ".cache" / "ear" / "sampler"


def _soulx_dir() -> Path:
    """``.cache/ear/soulx`` without importing the music21-dependent material script."""
    return paths.copyist_root() / ".cache" / "ear" / "soulx"


def _ok_clip_dirs(system_dir: Path, clips_dir: Path) -> set[str]:
    """Clip ids under ``clips_dir`` whose ``jobs.Job`` ``done.json`` (under ``system_dir``) says status ok."""
    done = set()
    if not system_dir.exists():
        return done
    for done_path in system_dir.glob("*/done.json"):
        from . import jobs
        record = jobs.read_json(done_path)
        if record and record.get("status") == "ok":
            done.add(done_path.parent.name)
    return done


def sampler_clips_for(seed: int, out: Path | None = None) -> list[dict]:
    """Every accepted sampler variant for one sampler seed -> train clip dicts (wav + by-construction labels)."""
    out = Path(out or _sampler_dir())
    clips_dir = out / "clips"
    ok = _ok_clip_dirs(out / "ear-sampler", clips_dir)
    found = []
    for clip_dir in sorted(clips_dir.glob(f"{seed}-v*")):
        if clip_dir.name not in ok:
            continue
        wav, labels = clip_dir / "audio.wav", clip_dir / "labels.json"
        if wav.exists() and labels.exists():
            found.append({"id": f"sampler-{seed}:{clip_dir.name}", "wav": wav, "labels": labels})
    return found


def soulx_clips_for(seed: int, out: Path | None = None) -> list[dict]:
    """Every accepted SoulX clip for one soulx seed -> train clip dicts (vocal wav + by-construction labels)."""
    out = Path(out or _soulx_dir())
    clips_dir = out / "clips"
    ok = _ok_clip_dirs(out / "ear-soulx", clips_dir)
    found = []
    for clip_dir in sorted(clips_dir.glob(f"{seed}-*")):
        if clip_dir.name not in ok:
            continue
        wav, labels = clip_dir / "vocal.wav", clip_dir / "labels.json"
        if wav.exists() and labels.exists():
            found.append({"id": f"soulx-{seed}:{clip_dir.name}", "wav": wav, "labels": labels})
    return found


def _seed_of(member_id: str, prefix: str) -> int:
    """``sampler-90000000`` -> 90000000 (the integer seed after ``<prefix>-``)."""
    return int(member_id[len(prefix) + 1:])


def train_clips(sampler_out: Path | None = None, soulx_out: Path | None = None) -> list[dict]:
    """All TRAIN clips: sampler-dev + soulx-dev, resolved from the frozen split member ids."""
    clips: list[dict] = []
    for member in dev_splits.sampler_dev_seeds():
        clips.extend(sampler_clips_for(_seed_of(member, "sampler"), sampler_out))
    for member in dev_splits.soulx_dev_seeds():
        clips.extend(soulx_clips_for(_seed_of(member, "soulx"), soulx_out))
    return clips


def reference_to_eval_labels(reference_tsv: Path, item: dict) -> dict:
    """Adapt a real-dev reference TSV into **melody-only** eval labels (owner's Option 1 decision).

    The RWC/karaoke references are note-only TSVs (``note_id onset offset midi midi_sung mask source``,
    ``refs.py``); they carry melody notes with a karaoke freestyle mask, but no beats, downbeats, chords, key
    or duration. Under Option 1 (melody-only real-dev eval) the real recordings are scored on melody only:

    - ``notes`` carries each reference note as ``{"onset","offset","midi","mask"}``. ``midi`` is the written
      pitch; octave-exact scoring uses it directly (``score_one_clip``). A note's ``mask`` string is preserved
      (``""`` scored, ``"freestyle"`` a don't-care) so the strict scorer's existing don't-care logic applies.
    - ``duration`` = max note offset + ``TAIL`` (or ``TAIL`` when there are no notes).
    - ``beats``, ``downbeats``, ``chords``, ``key_class``, ``meter`` and ``tempo`` are all set to the
      NOT-LABELLED sentinel ``None`` (distinct from ``[]`` "labelled empty" and ``0`` "labelled zero"), so the
      scorer excludes those heads from this clip's metrics and from ``decide()``'s means rather than scoring
      them as all-wrong against invented truth.

    ``item`` is the manifest item (unused here; kept so the resolver can pass per-item context). Import-light
    (numpy-only ``notes_io``) so it runs in the torch-only probe-eval env.
    """
    ref = notes_io.load_reference(Path(reference_tsv))
    notes = [{"onset": float(on), "offset": float(off), "midi": int(midi), "mask": str(mask)}
             for on, off, midi, mask in zip(ref.onset, ref.offset, ref.midi, ref.mask)]
    duration = (max(n["offset"] for n in notes) + TAIL) if notes else TAIL
    return {
        "format": "ear-eval-labels/melody-only-1",
        "duration": duration,
        "notes": notes,
        "beats": None,
        "downbeats": None,
        "chords": None,
        "key_class": None,
        "meter": None,
        "tempo": None,
    }


def _manifest_item(member_id: str) -> tuple[dict, dict]:
    """(manifest, item) for a real-dev id (``rwc-*`` or ``usdx-*``)."""
    from . import manifests
    name = "rwc-other" if member_id.startswith("rwc-") else "usdx"
    manifest = manifests.load(name)
    for item in manifest["items"]:
        if item["id"] == member_id:
            return manifest, item
    raise KeyError(f"{member_id} not found in manifest {name}")


def real_dev_clips(data: Path | None = None, *, label_adapter=reference_to_eval_labels) -> list[dict]:
    """REAL-DEV eval clips: rwc-other-dev + karaoke-dev, as ``{"id","wav","labels"}``.

    The wav is the manifest's decoded audio (under the data folder); the labels come from ``label_adapter``
    applied to the item's reference. The default adapter (``reference_to_eval_labels``) builds melody-only
    eval labels (Option 1); tests inject a fake adapter to exercise assembly without touching the real files.
    """
    data = Path(data or paths.data_dir())
    members = dev_splits.rwc_other_dev() + dev_splits.karaoke_dev(data=data)
    clips = []
    for member in sorted(members):
        _manifest, item = _manifest_item(member)
        audio = item.get("audio")
        if not audio:
            continue
        wav = data / audio["path"]
        reference = item.get("reference")
        reference_tsv = data / reference["path"] if reference else None
        clips.append({"id": member, "wav": wav, "labels": label_adapter(reference_tsv, item)})
    return clips


def assemble(sampler_out: Path | None = None, soulx_out: Path | None = None, data: Path | None = None,
             *, label_adapter=reference_to_eval_labels) -> tuple[list[dict], list[dict]]:
    """(train_clips, real_dev_clips) for a run, refusing any sealed TEST-partition id (fail closed)."""
    train = train_clips(sampler_out, soulx_out)
    dev = real_dev_clips(data, label_adapter=label_adapter)
    _guard_no_sealed_ids([c["id"] for c in dev])
    return train, dev


def _guard_no_sealed_ids(ids: list[str]) -> None:
    """Refuse any sealed TEST-partition id (RWC-Pop, rwc-other-test, USDX-test) or a COTB id."""
    sealed = dev_splits.test_partition_ids()
    leaked = sorted(set(ids) & sealed)
    if leaked:
        raise ValueError(f"refusing to assemble sealed test-partition ids: {leaked}")
    if any(str(i).lower().startswith("cotb") for i in ids):
        raise ValueError("refusing to assemble COTB ids")
